import { readdir, readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
const root = new URL('../dist/', import.meta.url);
async function files(directory = '', result = []) {
  for (const item of await readdir(new URL(directory, root), { withFileTypes: true })) {
    const name = directory + item.name;
    if (name === 'marketplace') continue;
    if (item.isDirectory()) await files(name + '/', result);
    else if (/\.(html|mjs|js|css|wasm|png|gif)$/.test(name) && name !== 'sw.js') result.push(name);
  }
  return result;
}
const assets = (await files()).sort(),
  hash = createHash('sha256');
for (const name of assets) hash.update(name).update(await readFile(new URL(name, root)));
const source = `// Generated by scripts/build-shell.mjs. No API data or credentials are cached.
const CACHE='oka-chat-shell-${hash.digest('hex').slice(0, 16)}';
const ASSETS=${JSON.stringify(['/', ...assets.map((name) => '/' + name)])};
self.addEventListener('install',event=>event.waitUntil(caches.open(CACHE).then(cache=>cache.addAll(ASSETS)).then(()=>self.skipWaiting())));
self.addEventListener('activate',event=>event.waitUntil(caches.keys().then(keys=>Promise.all(keys.filter(key=>key.startsWith('oka-chat-shell-')&&key!==CACHE).map(key=>caches.delete(key)))).then(()=>self.clients.claim())));
self.addEventListener('fetch',event=>{
 const url=new URL(event.request.url);
 if(event.request.method!=='GET'||url.origin!==self.location.origin||url.pathname.startsWith('/api/')||!ASSETS.includes(url.pathname))return;
 event.respondWith((async()=>{const cache=await caches.open(CACHE);try{const response=await fetch(event.request);if(response.ok)await cache.put(url.pathname,response.clone());return response;}catch{const saved=await cache.match(url.pathname);return saved||Response.error();}})());
});
`;
await writeFile(new URL('sw.js', root), source);
